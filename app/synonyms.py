def seed() -> int:
    return synonymdb.import_many(SEED, author="seed")


def seed_if_empty() -> int:
    synonymdb.ensure_schema()
    if synonymdb.count() == 0 and settings.bool_value("SYNONYMS_SEED_ON_START", config.SYNONYMS_SEED_ON_START):
        return seed()
    return synonymdb.count()


def main() -> None:
    import argparse

    parser = argparse.ArgumentParser(description="Наполнение БД синонимов")
    parser.add_argument("--replace", action="store_true", help="заменить каталог")
    args = parser.parse_args()

    os.makedirs(os.path.dirname(config.SYNONYMS_DB), exist_ok=True)
    if args.replace:
        synonymdb.ensure_schema()
        with synonymdb.connect() as conn:
            conn.execute("DELETE FROM synonyms")
        synonymdb.invalidate()
    total = seed()
    synonymdb.invalidate()
    print(f"терминов в БД: {total}")


if __name__ == "__main__":
    main()
