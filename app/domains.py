_seed_done = False


def _base_prompt() -> str:
    return settings.value("SYSTEM_PROMPT", config.SYSTEM_PROMPT)


def ensure_seed() -> None:
    """Наполнить таблицу направлений встроенным каталогом при первом запуске."""
    global _seed_done
    if _seed_done:
        return
    appdb.ensure_schema()
    if appdb.count_domains() == 0:
        base = _base_prompt()
        for item in SEED:
            _insert_item(item, base)
    _migrate_seed()
    _seed_done = True


def _insert_item(item: dict, base: str) -> dict:
    addon = item.get("addon", "")
    prompt = f"{base}\n\n{addon}" if addon else base
    return appdb.insert_domain(
        slug=item["slug"],
        title=item["title"],
        description=item.get("description", ""),
        system_prompt=prompt,
        capabilities=item.get("capabilities", []),
        categories=item.get("categories", []),
        terminology=item.get("terminology", []),
        sample_questions=item.get("sample_questions", []),
        temperature=item.get("temperature"),
        allow_inference=bool(item.get("allow_inference", False)),
        log_analysis=bool(item.get("log_analysis", False)),
        settings=item.get("settings") or {},
        synonyms=item.get("synonyms") or {},
        is_builtin=True,
    )


def _stored_seed_version() -> int:
    raw = (appdb.get_setting(SEED_VERSION_KEY, "") or "").strip()
    try:
        return int(raw)
    except ValueError:
        return 0


def _migrate_seed() -> None:
    """Досыпать новые встроенные направления и примеры вопросов в существующую БД."""
    if _stored_seed_version() >= SEED_VERSION:
        return
    base = _base_prompt()
    for item in SEED:
        existing = appdb.get_domain_by_slug(item["slug"])
        if not existing:
            _insert_item(item, base)
            continue
        fields: dict = {}
        if not existing.get("is_builtin"):
            fields["is_builtin"] = True
        current = list(existing.get("sample_questions") or [])
        known = {q.strip().lower() for q in current}
        merged = list(current)
        for question in item.get("sample_questions", []):
            key = question.strip().lower()
            if key and key not in known:
                merged.append(question)
                known.add(key)
        if merged != current:
            fields["sample_questions"] = merged
        addon = item.get("addon", "")
        prompt = f"{base}\n\n{addon}" if addon else base
        if (existing.get("system_prompt") or "").strip() != prompt.strip():
            fields["system_prompt"] = prompt
        if "temperature" in item and existing.get("temperature") != item.get("temperature"):
            fields["temperature"] = item.get("temperature")
        if "allow_inference" in item and bool(existing.get("allow_inference")) != bool(
            item.get("allow_inference")
        ):
            fields["allow_inference"] = bool(item.get("allow_inference"))
        if "log_analysis" in item and bool(existing.get("log_analysis")) != bool(
            item.get("log_analysis")
        ):
            fields["log_analysis"] = bool(item.get("log_analysis"))
        if item.get("settings") is not None and existing.get("settings") != item.get("settings"):
            fields["settings"] = item.get("settings") or {}
        if item.get("synonyms") is not None and existing.get("synonyms") != item.get("synonyms"):
            fields["synonyms"] = item.get("synonyms") or {}
        if fields:
            appdb.update_domain(item["slug"], **fields)
    appdb.set_setting(SEED_VERSION_KEY, str(SEED_VERSION))
    settings.invalidate()


def slugify(title: str) -> str:
    text = (title or "").strip().lower()
    text = "".join(_TRANSLIT.get(ch, ch) for ch in text)
    text = re.sub(r"[^a-z0-9]+", "-", text).strip("-")
    return text or "domain"


def _unique_slug(base: str, exclude: str | None = None) -> str:
    candidate = base
    index = 2
    while True:
        existing = appdb.get_domain_by_slug(candidate)
        if not existing or candidate == exclude:
            return candidate
        candidate = f"{base}-{index}"
        index += 1


def list_profiles() -> list[dict]:
    """Полный каталог направлений для кабинета (по алфавиту)."""
    ensure_seed()
    return sorted(
        appdb.list_domains(),
        key=lambda item: (item.get("title") or "").casefold().replace("ё", "е"),
    )


def current_id() -> str:
    ensure_seed()
    domains = appdb.list_domains()
    if not domains:
        return ""
    known = {item["slug"] for item in domains}
    stored = (appdb.get_setting(SETTING_KEY, "") or "").strip()
    if stored in known:
        return stored
    env = (config.DOMAIN_PROFILE or "").strip()
    if env in known:
        return env
    if DEFAULT_SLUG in known:
        return DEFAULT_SLUG
    return domains[0]["slug"]


def current() -> dict:
    ensure_seed()
    item = appdb.get_domain_by_slug(current_id())
    if item:
        return item
    domains = appdb.list_domains()
    return domains[0] if domains else {}


def set_profile(slug: str) -> dict:
    ensure_seed()
    if not appdb.get_domain_by_slug(slug):
        raise ValueError(f"Неизвестное направление: {slug}")
    appdb.set_setting(SETTING_KEY, slug)
    settings.invalidate()
    _invalidate_synonyms()
    return current()


def reset() -> dict:
    appdb.set_setting(SETTING_KEY, "")
    settings.invalidate()
    _invalidate_synonyms()
    return current()


def _invalidate_synonyms() -> None:
    try:
        import synonymdb

        synonymdb.invalidate()
    except Exception:
        pass


def system_prompt() -> str:
    """Системная инструкция активного направления (иначе — общая из настроек)."""
    item = current()
    prompt = (item.get("system_prompt") or "").strip()
    if prompt and item.get("allow_inference"):
        prompt = f"{prompt}\n\n{INFERENCE_BLOCK}"
    return prompt or _base_prompt()


def temperature() -> float | None:
    """Температура генерации направления; None — использовать общую."""
    value = current().get("temperature")
    if value is None:
        return None
    try:
        number = float(value)
    except (TypeError, ValueError):
        return None
    return number if number >= 0 else None


