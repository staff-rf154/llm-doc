def active_settings() -> dict:
    """Настройки активной сферы деятельности: имеют приоритет над локальными."""
    item = current()
    values = item.get("settings") or {}
    return {str(k): str(v) for k, v in values.items() if str(v).strip()}


def active_synonyms() -> dict[str, list[str]]:
    """Синонимы активной сферы деятельности."""
    item = current()
    values = item.get("synonyms") or {}
    result: dict[str, list[str]] = {}
    for term, synonyms in values.items():
        key = str(term).strip().lower()
        if not key:
            continue
        if isinstance(synonyms, str):
            synonyms = [part.strip() for part in synonyms.split(",")]
        clean = [str(s).strip() for s in (synonyms or []) if str(s).strip()]
        if clean:
            result[key] = clean
    return result


def _clean_settings(raw) -> dict:
    if not isinstance(raw, dict):
        return {}
    import settings as settings_mod

    known = {param.key for param in settings_mod.PARAMS}
    result: dict = {}
    for key, value in raw.items():
        name = str(key).strip()
        if name not in known:
            continue
        text = "" if value is None else str(value).strip()
        if text:
            result[name] = text
    return result


def _clean_synonyms(raw) -> dict:
    if not isinstance(raw, dict):
        return {}
    result: dict[str, list[str]] = {}
    for term, synonyms in raw.items():
        key = str(term).strip().lower()
        if not key:
            continue
        if isinstance(synonyms, str):
            synonyms = [part.strip() for part in synonyms.split(",")]
        clean = [str(s).strip() for s in (synonyms or []) if str(s).strip()]
        if clean:
            result[key] = clean
    return result


def _clean_temperature(raw) -> float | None:
    if raw is None or raw == "":
        return None
    try:
        number = float(raw)
    except (TypeError, ValueError):
        return None
    if number < 0 or number > 2:
        return None
    return round(number, 2)


def _clean_list(raw) -> list[str]:
    if not isinstance(raw, list):
        return []
    return [str(item).strip() for item in raw if str(item).strip()]


def _clean_groups(raw) -> list[dict]:
    if not isinstance(raw, list):
        return []
    groups: list[dict] = []
    for group in raw:
        if not isinstance(group, dict):
            continue
        title = str(group.get("title", "")).strip()
        items = _clean_list(group.get("items"))
        if title and items:
            groups.append({"title": title, "items": items})
    return groups
